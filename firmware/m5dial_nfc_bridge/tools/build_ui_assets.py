#!/usr/bin/env python3
"""Encode the approved generated background and rasterize a small OFL font subset."""
import argparse,hashlib,json,re,struct
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
fw=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--font',required=True);a=p.parse_args()
im=Image.open(fw/'assets/dial-workbench-v2.png').convert('RGB').resize((240,240),Image.Resampling.LANCZOS)
raw=b''.join(struct.pack('>H',((r>>3)<<11)|((g>>2)<<5)|(b>>3)) for r,g,b in im.getdata())
(fw/'assets/dial-workbench-v2.rgb565').write_bytes(raw)
# Include exactly the static status vocabulary plus ASCII for UID/percent/version.
text=(fw/'main/ui_model.c').read_text()+'PULSE NFC 身份终端已连接未连接静音按键开声正在检查硬件版本请使用卡片等待读取写入校验成功失败请勿移开声'
chars=sorted(set(chr(i) for i in range(32,127))|set(re.findall('[\u3400-\u9fff]',text)))
glyphs=[];bits=[]
for size in (12,18):
 font=ImageFont.truetype(a.font,size)
 for ch in chars:
  width=max(1,int(font.getlength(ch)+1));height=size+4
  tile=Image.new('L',(width,height));ImageDraw.Draw(tile).text((0,0),ch,font=font,fill=255,anchor='lt')
  offset=len(bits);rowbytes=(width+7)//8
  for y in range(height):
   for bx in range(rowbytes):
    byte=0
    for b in range(8):
     x=bx*8+b
     if x<width and tile.getpixel((x,y))>=96:byte|=128>>b
    bits.append(byte)
  glyphs.append((ord(ch),size,width,height,width,offset))
header='''/* Generated by tools/build_ui_assets.py. Noto Sans CJK, SIL OFL; see assets/OFL-Noto.txt. */
#include "ui_font.h"
const ui_glyph_t ui_glyphs[]={\n'''+''.join('{'+','.join(map(str,g))+'},\n' for g in glyphs)+'};\nconst unsigned ui_glyph_count=sizeof ui_glyphs/sizeof ui_glyphs[0];\nconst unsigned char ui_font_bits[]={\n'
for i in range(0,len(bits),32):header+=','.join(str(x) for x in bits[i:i+32])+',\n'
header+='};\n';(fw/'main/ui_font.c').write_text(header)
print('UI background',len(raw),'bytes; font',len(glyphs),'glyphs',len(bits),'bytes')
